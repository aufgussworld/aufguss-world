-- ── STRAŻNIK PRZY ZAPISIE ───────────────────────────────────────────────────
create or replace function public.guard_content_report()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_scope text;
  v_day   integer;
  v_week  integer;
  v_cnt   integer;
begin
  new.reporter_email := nullif(lower(trim(new.reporter_email)), '');

  -- 1. blokada
  if public.is_report_blocked(new.reporter_id, new.reporter_email) then
    raise exception 'Zgłoszenia z tego konta zostały wstrzymane.'
      using errcode = 'check_violation', hint = 'report_blocked';
  end if;

  -- 2. limit dobowy i tygodniowy
  v_scope := case when new.reporter_id is not null then 'authenticated' else 'anonymous' end;
  select per_day, per_week into v_day, v_week from public.report_limits where scope = v_scope;

  select count(*) into v_cnt from public.content_reports r
  where r.created_at > now() - interval '1 day'
    and ((new.reporter_id is not null and r.reporter_id = new.reporter_id)
      or (new.reporter_id is null and r.reporter_email = new.reporter_email));
  if v_cnt >= v_day then
    raise exception 'Dzienny limit zgłoszeń (%) został wyczerpany. Spróbuj jutro.', v_day
      using errcode = 'check_violation', hint = 'rate_limit_day';
  end if;

  select count(*) into v_cnt from public.content_reports r
  where r.created_at > now() - interval '7 days'
    and ((new.reporter_id is not null and r.reporter_id = new.reporter_id)
      or (new.reporter_id is null and r.reporter_email = new.reporter_email));
  if v_cnt >= v_week then
    raise exception 'Tygodniowy limit zgłoszeń (%) został wyczerpany.', v_week
      using errcode = 'check_violation', hint = 'rate_limit_week';
  end if;

  -- 3. bez duplikatów: jedno OTWARTE zgłoszenie do tej samej treści i wersji językowej
  select count(*) into v_cnt from public.content_reports r
  where r.status in ('new','in_progress')
    and r.locale is not distinct from new.locale
    and r.venue_id is not distinct from new.venue_id
    and r.event_id is not distinct from new.event_id
    and r.post_id is not distinct from new.post_id
    and r.training_id is not distinct from new.training_id
    and r.tournament_id is not distinct from new.tournament_id
    and r.comment_id is not distinct from new.comment_id
    and ((new.reporter_id is not null and r.reporter_id = new.reporter_id)
      or (new.reporter_id is null and r.reporter_email = new.reporter_email));
  if v_cnt > 0 then
    raise exception 'Zgłosiłeś już tę treść — uwaga czeka na rozpatrzenie.'
      using errcode = 'unique_violation', hint = 'duplicate_report';
  end if;

  return new;
end $$;

