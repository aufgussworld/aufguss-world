-- ── REPUTACJA ZGŁASZAJĄCEGO ─────────────────────────────────────────────────
-- Właściciel treści widzi, czy ma do czynienia z kimś, kto zwykle trafia,
-- czy z kimś, komu odrzucono już wszystko. To zmienia sposób czytania uwagi.
create or replace view public.reporter_reputation as
  select
    r.reporter_id,
    r.reporter_email,
    count(*)                                              as zgloszen,
    count(*) filter (where r.status = 'resolved')          as potwierdzonych,
    count(*) filter (where r.status = 'rejected')          as odrzuconych,
    count(*) filter (where r.status in ('new','in_progress')) as otwartych,
    case when count(*) filter (where r.status in ('resolved','rejected')) = 0 then null
         else round(100.0 * count(*) filter (where r.status = 'resolved')
                    / count(*) filter (where r.status in ('resolved','rejected')))
    end                                                    as trafnosc_proc
  from public.content_reports r
  group by r.reporter_id, r.reporter_email;

-- ── AUTOMATYCZNA BLOKADA ────────────────────────────────────────────────────
-- Po odrzuceniu zgłoszenia sprawdzamy dorobek autora. Pięć odrzuceń bez ani
-- jednego trafienia = 30 dni przerwy. Wystarczy JEDNO potwierdzone zgłoszenie,
-- żeby automat nie zadziałał — nie karzemy ludzi, którzy czasem się mylą.
create or replace function public.autoblock_after_rejections()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_rej integer; v_ok integer;
begin
  if new.status <> 'rejected' or old.status = 'rejected' then return new; end if;

  select count(*) filter (where status = 'rejected'),
         count(*) filter (where status = 'resolved')
    into v_rej, v_ok
  from public.content_reports
  where (new.reporter_id is not null and reporter_id = new.reporter_id)
     or (new.reporter_id is null and reporter_email = new.reporter_email);

  if v_rej >= 5 and v_ok = 0 then
    insert into public.report_blocks (profile_id, email, reason, blocked_until, is_automatic)
    values (new.reporter_id, new.reporter_email,
            format('Automat: %s odrzuconych zgłoszeń bez potwierdzonego.', v_rej),
            now() + interval '30 days', true)
    on conflict do nothing;
  end if;
  return new;
end $$;

create trigger content_reports_autoblock
  after update of status on public.content_reports
  for each row execute function public.autoblock_after_rejections();

